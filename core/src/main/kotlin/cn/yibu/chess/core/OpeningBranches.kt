        notes: String, at: Int, prompt: String, identity: Int = base.identityPlies): OpeningRoute {
        val moves = base.moves.take(prefix) + tail.split(' ')
        val reasons = base.notes.take(prefix) + notes.trimIndent().lines().map(String::trim)
        return OpeningRoute(id, title, moves, reasons, OpeningCheckpoint(at, prompt,
            "先考虑 ${moves[at].take(2)} 的棋子，检查它能否完成目标。", mapOf(moves[at] to reasons[at])), identity)
    }

